"""Check the resource-bound inventory against the public API (M2-04).

Every public function whose @time annotation is not exactly "O(1)" must name its cost
inputs in docs/engineering/resource-bounds.json, every name must be an inventory entry,
and every entry must state its input, bound, limit, enforcement and whether it runs
masked. The inventory's rendered page, resource-bounds.md, must match the JSON
(--write regenerates it). Exit status 1 on any mismatch.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "docs"))
from build import contract_tags  # noqa: E402

INVENTORY = ROOT / "docs" / "engineering" / "resource-bounds.json"
PAGE = ROOT / "docs" / "engineering" / "resource-bounds.md"
FIELDS = ("id", "input", "bound", "limit", "enforcement", "masked", "profiles", "evidence")
ENFORCEMENT = {"configuration", "admission", "structural", "application"}
BLOCK = re.compile(r"/\*\*\s*\n\s*\* (emb_[a-z0-9_]+)\(\) -.*?\*/", re.S)


def annotated_costs(include: Path = ROOT / "include" / "emb") -> dict:
    """Public function -> its @time text, for every non-O(1) annotation."""
    out = {}
    for header in sorted(include.glob("*.h")):
        for m in BLOCK.finditer(header.read_text(encoding="utf-8")):
            t = contract_tags(m.group(0)).get("time", "")
            if t != "O(1)":
                out[m.group(1)] = t
    return out


def problems(inv: dict, costs: dict) -> list:
    errs = []
    ids = set()
    for b in inv["bounds"]:
        missing = [f for f in FIELDS if f not in b or b[f] in ("", None)]
        if missing:
            errs.append(f"bound {b.get('id', '?')}: missing {', '.join(missing)}")
        if b.get("enforcement") not in ENFORCEMENT:
            errs.append(f"bound {b.get('id')}: enforcement {b.get('enforcement')!r} not one of {sorted(ENFORCEMENT)}")
        if b.get("id") in ids:
            errs.append(f"bound {b['id']}: duplicate")
        ids.add(b.get("id"))
    for fn in sorted(set(costs) - set(inv["apis"])):
        errs.append(f"{fn}: @time {costs[fn]!r} has no inventory entry")
    for fn in sorted(set(inv["apis"]) - set(costs)):
        errs.append(f"{fn}: listed in the inventory but its @time is O(1) or it is not public")
    for fn, refs in sorted(inv["apis"].items()):
        for ref in refs:
            if ref not in ids:
                errs.append(f"{fn}: unknown bound {ref!r}")
    return errs


def render(inv: dict, costs: dict) -> str:
    lines = ["<!-- Generated by tools/evidence/check_bounds.py from resource-bounds.json; do not edit. -->",
             "", "# Resource-bound inventory", "",
             "Every cost input named by a public function's `@time` annotation, with how it is bounded. "
             "The inventory is reviewed, not derived: the checker proves only that it is complete "
             "against the annotations. Analysis and measured worst cases attach to these entries as they "
             "are produced; [timing and evidence](timing-and-evidence.md) defines how a claim becomes "
             "substantiated.", "",
             "| Input | Bound | Limit | Enforcement | Masked | Profiles | Evidence |",
             "|---|---|---|---|---|---|---|"]
    for b in inv["bounds"]:
        lines.append(f"| **{b['id']}**: {b['input']} | {b['bound']} | {b['limit']} | {b['enforcement']} | "
                     f"{'yes' if b['masked'] else 'no'} | {b['profiles']} | {b['evidence']} |")
    lines += ["", "## Public functions", "", "| Function | `@time` | Inputs |", "|---|---|---|"]
    for fn in sorted(inv["apis"]):
        lines.append(f"| `{fn}()` | {costs.get(fn, '')} | {', '.join(inv['apis'][fn])} |")
    return "\n".join(lines) + "\n"


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true", help="regenerate resource-bounds.md")
    args = ap.parse_args(argv)
    inv = json.loads(INVENTORY.read_text(encoding="utf-8"))
    costs = annotated_costs()
    errs = problems(inv, costs)
    page = render(inv, costs)
    if args.write:
        PAGE.write_text(page, encoding="utf-8")
    elif not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page:
        errs.append(f"{PAGE.relative_to(ROOT)} is out of date: run check_bounds.py --write")
    for e in errs:
        print(f"check_bounds: {e}", file=sys.stderr)
    if not errs:
        print(f"check_bounds: {len(inv['bounds'])} bounds cover {len(costs)} non-O(1) public functions")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
