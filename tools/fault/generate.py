"""Generate stable numeric API definitions and decoder metadata from explicit IDs."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = Path('tools/fault/api-registry.json')
HEADER = Path('include/emb/api_ids.h')
DECODER = Path('tools/fault/api-ids.json')


def validate(data):
    if data.get('schema_version') != 1 or not isinstance(data.get('apis'), list):
        raise ValueError('unsupported registry schema')
    ids, names = set(), set()
    for api in data['apis']:
        if (type(api['id']) is not int or not 1 <= api['id'] <= 65535 or
                not re.fullmatch(r'emb_[a-z0-9_]+', api['name']) or
                not re.fullmatch(r'[a-z0-9_]+\.h', api['header']) or
                api['state'] not in ('active', 'retired')):
            raise ValueError(f'invalid API entry: {api}')
        if api['id'] in ids or api['name'] in names:
            raise ValueError('duplicate API number or name')
        ids.add(api['id'])
        names.add(api['name'])
    return sorted(data['apis'], key=lambda api: api['id'])


def compatible(old, new):
    current = {api['id']: api for api in validate(new)}
    for api in validate(old):
        found = current.get(api['id'])
        if found is None or found['name'] != api['name']:
            raise ValueError(f"API {api['id']} ({api['name']}) removed or renumbered; retain retired entries")
        if api['state'] == 'retired' and found['state'] != 'retired':
            raise ValueError('retired API IDs must not be reactivated')


def outputs(data):
    apis = validate(data)
    lines = ['/* Generated by tools/fault/generate.py; explicit IDs must never be renumbered. */',
             '/* SPDX-License-Identifier: Apache-2.0 */', '#ifndef EMB_API_IDS_H',
             '#define EMB_API_IDS_H', '']
    defines = [('EMB_API_ID_NONE', 0)] + [('EMB_API_ID_' + api['name'][4:].upper(), api['id']) for api in apis]
    width = max(len(name) for name, _ in defines)
    for name, value in defines:
        lines.append(f"#define {name:<{width}} 0x{value:04X}u")
    lines += ['', '#endif /* EMB_API_IDS_H */', '']
    decoder = dict(schema_version=1, unknown_id=0, apis=apis)
    return {HEADER: '\n'.join(lines), DECODER: json.dumps(decoder, indent=2) + '\n'}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--baseline', help='Git commit containing the previous registry, if any')
    args = parser.parse_args()
    data = json.loads((ROOT/REGISTRY).read_text())
    if args.baseline and args.baseline != '0'*40:
        if not re.fullmatch(r'[a-fA-F0-9]{40}', args.baseline):
            raise ValueError('baseline must be a full commit SHA')
        # A first registry has no predecessor. Distinguish absence from Git errors.
        tree = subprocess.check_output(['git', 'ls-tree', args.baseline, '--', str(REGISTRY)],
                                       cwd=ROOT, text=True)
        if tree.strip():
            old = json.loads(subprocess.check_output(
                ['git', 'show', f'{args.baseline}:{REGISTRY}'], cwd=ROOT, text=True))
            compatible(old, data)
    for path, content in outputs(data).items():
        target = ROOT/path
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise ValueError(f'{path} is stale; run tools/fault/generate.py')
        else:
            target.write_text(content)
    print(f"API IDs: {len(validate(data))} explicit entries; generated outputs {'checked' if args.check else 'written'}")


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, subprocess.CalledProcessError) as error:
        sys.exit(f'API ID check failed: {error}')
