import hashlib
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import sbom  # noqa: E402

GNU_MAP = """Archive member included to satisfy reference by file (symbol)

emblinkrtos/kernel/libemb_kernel.a(sched.c.obj)
                              CMakeFiles/controller.dir/main.c.obj (emb_kernel_start)
/opt/arm/lib/libc_nano.a(libc_a-memset.o)
                              emblinkrtos/kernel/libemb_kernel.a(thread.c.obj) (memset)

Memory Configuration
LOAD CMakeFiles/controller.dir/main.c.obj
LOAD emblinkrtos/kernel/libemb_kernel.a
LOAD /opt/arm/lib/libgcc.a
"""

LLD_MAP = """     VMA      LMA     Size Align Out     In      Symbol
 8000000  8000000      200     4 .vectors
 8000000  8000000      200     4         emblinkrtos/arch/cortex_m/libemb_arch.a(cm_vectors.c.obj):(.vectors)
 8000200  8000200       10     4         CMakeFiles/controller.dir/main.c.obj:(.text.main)
 8000210  8000210        8     4         /opt/arm/lib/libgcc.a(_aeabi_uldivmod.o):(.text)
"""


class LinkMaps(unittest.TestCase):
    def test_gnu_ld(self):
        members, objects = sbom.linked_inputs(GNU_MAP)
        # a member named as the referrer is linked too: it is what pulled the next one in
        self.assertEqual(members, {"emblinkrtos/kernel/libemb_kernel.a": {"sched.c.obj", "thread.c.obj"},
                                   "/opt/arm/lib/libc_nano.a": {"libc_a-memset.o"}})
        self.assertEqual(objects, {"CMakeFiles/controller.dir/main.c.obj"})

    def test_lld(self):
        members, objects = sbom.linked_inputs(LLD_MAP)
        self.assertEqual(members, {"emblinkrtos/arch/cortex_m/libemb_arch.a": {"cm_vectors.c.obj"},
                                   "/opt/arm/lib/libgcc.a": {"_aeabi_uldivmod.o"}})
        self.assertEqual(objects, {"CMakeFiles/controller.dir/main.c.obj"})


class Identity(unittest.TestCase):
    def test_build_id_and_configuration(self):
        with tempfile.TemporaryDirectory() as d:
            gen = Path(d) / "generated"
            gen.mkdir()
            (gen / "build_id.c").write_text(
                "/* SPDX-License-Identifier: Apache-2.0 */\n"
                "/* Generated by kernel/CMakeLists.txt: 0123abcd+dirty, configuration 0xdeadbeefu. */\n"
                "#include <embk/crash.h>\n\nEMB_FLASH_CONST uint8_t emb_build_id[EMB_CRASH_BUILD_ID_SIZE] = "
                "{0xAbu, 0x01u, };\n")
            (gen / "config.json").write_text(json.dumps({"hash": "ba51ed6cf894c22f"}))
            self.assertEqual(sbom.build_identity(d), ("0123abcd", True, "ba51ed6cf894c22f", "ab01"))

    def test_hardware_hash_is_order_independent(self):
        with tempfile.TemporaryDirectory() as d:
            hw = Path(d) / "boards/v/b/generated"
            hw.mkdir(parents=True)
            inputs = [{"path": "soc/x.yaml", "sha256": "22"}, {"path": "boards/v/b/board.yaml", "sha256": "11"}]
            (hw / "hw.json").write_text(json.dumps({"inputs": inputs}))
            digest, paths = sbom.hardware_hash(d, "b")
            text = "boards/v/b/board.yaml 11\nsoc/x.yaml 22\n"
            self.assertEqual(digest, hashlib.sha256(text.encode()).hexdigest())
            self.assertEqual(sorted(paths), ["boards/v/b/board.yaml", "soc/x.yaml"])
            self.assertEqual(sbom.hardware_hash(d, "none"), (None, []))


class Licences(unittest.TestCase):
    def test_c_cmake_and_none(self):
        with tempfile.TemporaryDirectory() as d:
            c, cm, none = Path(d) / "a.c", Path(d) / "b.cmake", Path(d) / "c.c"
            c.write_text("/* SPDX-License-Identifier: Apache-2.0 */\nint x;\n")
            cm.write_text("# SPDX-License-Identifier: MIT OR Apache-2.0\n")
            none.write_text("int y;\n")
            self.assertEqual(sbom.licence_of(c), "Apache-2.0")
            self.assertEqual(sbom.licence_of(cm), "MIT OR Apache-2.0")
            self.assertEqual(sbom.licence_of(none), "NOASSERTION")

    def test_spdx_ids(self):
        self.assertEqual(sbom.spdx_id("libc_nano.a"), "libc-nano.a")


if __name__ == "__main__":
    unittest.main()
