/*******************************************************************************
  Function:
    void SYS_Initialize ( void *data )

  Remarks:
    See prototype in definitions.h.
 */
void SYS_Initialize(void *data)
{
    (void)data;

    /* The board: its clocks, pins and console */
    emb_board_init();

    /* The kernel: its objects, and the EARLY devices */
    emb_kernel_init();

    /* The application's interrupts */
    SYS_INT_Initialize();

    /* The tasks, each in its initial state */
    DOOR_Initialize();
    BLINK_Initialize();
}
