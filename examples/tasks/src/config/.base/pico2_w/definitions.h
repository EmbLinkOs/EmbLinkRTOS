/*******************************************************************************
  Function:
    void SYS_Initialize ( void *data )

  Summary:
     Initializes the board, the kernel and every task.

  Description:
    This function initializes the board (its clocks, pins and console), then the
    kernel (its objects and the EARLY devices), then the application's
    interrupts, then each task, in its initial state. The KERNEL devices start
    with the kernel, in SYS_Tasks().

  Precondition:
    None.

  Parameters:
    data - Unused; NULL.

  Returns:
    None.

  Example:
    <code>
    SYS_Initialize(NULL);
    while (true) {
        SYS_Tasks();
    }
    </code>

  Remarks:
    This function is called once, after reset, from main().
*/
void SYS_Initialize(void *data);

/*******************************************************************************
  Function:
    void SYS_Tasks ( void )

  Summary:
     Starts the kernel: the threads and the tasks run from here.

  Description:
    This function starts the KERNEL devices, then the scheduler, which runs the
    system's threads and each task's thread. It does not return.

  Precondition:
    SYS_Initialize() has run.

  Parameters:
    None.

  Returns:
    It does not return.

  Example:
    <code>
    SYS_Initialize(NULL);
    while (true) {
        SYS_Tasks();
    }
    </code>

  Remarks:
    Harmony calls its SYS_Tasks() in a loop; this one runs the scheduler and
    never comes back.
*/
void SYS_Tasks(void);

