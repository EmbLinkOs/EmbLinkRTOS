/*******************************************************************************
  Function:
    void BLINK_Initialize ( void )

  Summary:
     The blink task's initialization.

  Description:
    This function puts the task in its initial state, BLINK_STATE_DARK, and
    prepares its data, before the kernel starts its thread.

  Precondition:
    The board and the kernel are initialized. The KERNEL devices are not ready
    yet: use them from the task's states.

  Parameters:
    None.

  Returns:
    None.

  Example:
    <code>
    BLINK_Initialize();
    </code>

  Remarks:
    SYS_Initialize() calls it.
*/
void BLINK_Initialize(void);

/*******************************************************************************
  Function:
    void BLINK_Tasks ( void )

  Summary:
     The blink task's state machine.

  Description:
    This function runs the task's current state, blinkData.state, once: its
    thread calls it every 500 ms.

  Precondition:
    BLINK_Initialize() has run.

  Parameters:
    None.

  Returns:
    None.

  Example:
    <code>
    BLINK_Tasks();
    </code>

  Remarks:
    Its thread calls it on a period that does not drift; a period it overruns is
    counted, not run twice (KRN-TSK-004).
*/
void BLINK_Tasks(void);

