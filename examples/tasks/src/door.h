/* Application states

  Summary:
    The door task's states.

  Description:
    The states system.yaml declares for the task, in its order: they are the
    task runtime's numbers, which tasks.c checks. Declare a state in
    system.yaml, and regeneration adds it here, with its handler.
*/
typedef enum {
    /* The task's initial state. */
    DOOR_STATE_CLOSED = 0,
    DOOR_STATE_OPEN,
    DOOR_STATE_JAMMED,
} DOOR_STATES;

/* Application events

  Summary:
    The door task's own events.

  Description:
    Numbered from EMB_EV_USER, as system.yaml lists them; the runtime's own,
    such as EMB_EV_TIMEOUT, are below it. Post one with emb_task_post(DOOR_TASK,
    DOOR_EVENT_<EVENT>, value).
*/
typedef enum {
    DOOR_EVENT_OPEN = EMB_EV_USER,
    DOOR_EVENT_CLOSE,
    DOOR_EVENT_JAM,
} DOOR_EVENTS;

/* Application Data

  Summary:
    Holds the door task's data.

  Description:
    This structure holds the task's data: only the task's thread runs its
    handlers.

  Remarks:
    state is the state whose handler runs; the runtime keeps it
    (emb_task_state(DOOR_TASK)).
*/
typedef struct {
    /* The task's current state */
    DOOR_STATES state;

    /* The times the door opened */
    uint32_t opened;
} DOOR_DATA;

extern DOOR_DATA doorData;

