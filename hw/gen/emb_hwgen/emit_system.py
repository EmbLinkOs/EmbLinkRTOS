def task_h(r, t):
    n, N = t["name"], _sym(t["name"])
    event = t["model"] == "event"
    out = _head(r, f"{n}.h", f"{n}: {_task_what(t)}", f"The {n} task's states, " + ("events, " if event else "")
                + "data and functions.",
                _app_desc(f"This header declares what the {n} task's own file defines: its states, "
                          + ("its events, " if event else "") + f"its data, {N}_Initialize() and "
                          + (f"a handler for each state, which the task's thread runs for each event (SPEC-020)."
                             if event else f"{N}_Tasks(), which the task's thread calls every {t['period_ms']} ms, "
                                           "without drift (SPEC-020).")))
    out += f"\n#ifndef {N}_H\n#define {N}_H\n"
    out += _section("Included Files")
    out += '#include "configuration.h"\n\n#include <emb/emb.h>\n\n#include <stdbool.h>\n#include <stddef.h>\n'
    out += "#include <stdint.h>\n\n" + _cpp_open()
    out += _section("Type Definitions")
    out += _states_enum(t)
    if t["events"]:
        out += "\n" + _comment_block("Application events", f"The {n} task's own events.",
                                     "Numbered from EMB_EV_USER, as system.yaml lists them; the runtime's own, such "
                                     "as EMB_EV_TIMEOUT, are below it. Post one with emb_task_post("
                                     f"{N}_TASK, {N}_EVENT_<EVENT>, value).")
        out += "typedef enum {\n"
        for i, ev in enumerate(t["events"]):
            out += f"    {N}_EVENT_{_sym(ev)}" + (" = EMB_EV_USER" if i == 0 else "") + ",\n"
        out += f"}} {N}_EVENTS;\n"
    if t["event"]:
        out += "\n" + _comment_block("Application event", f"The {n} task's own event type.",
                                     "The events posted to the task (emb_task_post_event()): the runtime reads its "
                                     "first member, the id.")
        out += (f"typedef struct {{\n    uint32_t id; /* first: {N}_EVENTS, or the runtime's EMB_EV_* */\n"
                f"    uint32_t value;\n\n    /* TODO: Define the event's data. */\n}} {t['event']};\n")
    remarks = (f"state is the state whose handler runs; the runtime keeps it (emb_task_state({N}_TASK))." if event
               else f"{N}_Tasks() moves the task by setting state.")
    out += "\n" + _comment_block("Application Data", f"Holds the {n} task's data.",
                                 "This structure holds the task's data: only the task's thread runs its "
                                 + ("handlers." if event else f"{N}_Tasks()."), remarks)
    out += (f"typedef struct {{\n    /* The task's current state */\n    {N}_STATES state;\n\n"
            f"    /* TODO: Define any additional data used by the task. */\n}} {N}_DATA;\n\n"
            f"extern {N}_DATA {_data(t)};\n")
    out += _section("Application Initialization and State Machine Functions")
    out += _doc(f"void {N}_Initialize ( void )", f"The {n} task's initialization.",
                f"This function puts the task in its initial state, {N}_STATE_{_sym(t['initial'])}, and prepares its "
                "data, before the kernel starts its thread.",
                "The board and the kernel are initialized. The KERNEL devices are not ready yet: use them from the "
                "task's states.", [], "None.", [f"{N}_Initialize();"], "SYS_Initialize() calls it.")
    out += f"void {N}_Initialize(void);\n"
    if not event:
        out += "\n" + _doc(f"void {N}_Tasks ( void )", f"The {n} task's state machine.",
                           f"This function runs the task's current state, {_data(t)}.state, once: its thread calls it "
                           f"every {t['period_ms']} ms.",
                           f"{N}_Initialize() has run.", [], "None.", [f"{N}_Tasks();"],
                           "Its thread calls it on a period that does not drift; a period it overruns is counted, not "
                           "run twice (KRN-TSK-004).")
        out += f"void {N}_Tasks(void);\n"
    else:
        ev_t = _event_type(t)
        for k, st in enumerate(t["states"]):
            S = _pascal(st)
            other = t["states"][(k + 1) % len(t["states"])]
            example = ([f"return (event->id == {N}_EVENT_{_sym(t['events'][0])}) ? {N}_STATE_{_sym(other)} : "
                        f"{N}_STATE_{_sym(st)};"] if t["events"] else [f"return {N}_STATE_{_sym(st)};"])
            out += "\n" + _doc(f"{N}_STATES {N}_On{S} ( const {ev_t} *event )",
                               f"The {n} task's {st} state: one event.",
                               f"This function runs for each event the task receives in {N}_STATE_{_sym(st)}"
                               + (", and with EMB_EV_TIMEOUT when the state's timeout passes"
                                  if st in t["timeouts"] else "") + ". It returns the state to be in next: "
                               f"{N}_STATE_{_sym(st)} to stay.",
                               f"{N}_Initialize() has run; the kernel runs the task's thread.",
                               ["event - The event: its id and its value."], "The next state.", example,
                               "The task's thread calls it, one event at a time; no event is lost meanwhile "
                               "(KRN-TSK-001).")
            out += f"{N}_STATES {N}_On{S}(const {ev_t} *event);\n"
        for kind, names, word in (("entry", t["entry"], "Enter"), ("exit", t["exit"], "Exit")):
            for st in names:
                S = _pascal(st)
                out += "\n" + _doc(f"void {N}_{word}{S} ( void )",
                                   f"The {n} task's {st} state: its {kind} action.",
                                   f"This function runs as the task {'enters' if kind == 'entry' else 'leaves'} "
                                   f"{N}_STATE_{_sym(st)}" + (", after the old state's exit action" if kind == "entry"
                                                              else ", before the new state's entry action") + ".",
                                   f"{N}_Initialize() has run.", [], "None.", [f"{N}_{word}{S}();"],
                                   "The task's thread calls it (KRN-TSK-002).")
                out += f"void {N}_{word}{S}(void);\n"
    out += "\n" + _cpp_close() + f"\n#endif /* {N}_H */\n" + END_OF_FILE
    return out


