def _irq_lines(r):
    """Every interrupt line in use on the board: (number, who)."""
    lines = []
    for d in r["devices"]:
        for f in d["fields"]:
            if ".irqs." in str(f["expr"]) and isinstance(f["value"], int):
                lines.append((f["value"], f"{d['name']}, its driver ({f['expr']})"))
    for i in r["system"]["interrupts"]:
        lines.append((i["irq"], f"{i['name']}, the application's {i['handler']}()"))
    return sorted(set(lines))


