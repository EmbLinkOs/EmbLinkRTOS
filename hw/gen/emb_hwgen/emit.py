_CM_SECTIONS = """\
ENTRY(embn_cm_reset)

MEMORY
{{
  FLASH (rx)  : ORIGIN = 0x{flash_origin:08X}, LENGTH = {flash_length}
  RAM   (rwx) : ORIGIN = 0x{ram_origin:08X}, LENGTH = {ram_length}
}}

SECTIONS
{{
  /* the vector table, then any block the SoC's boot ROM looks for near the image's start
     (the RP2350's IMAGE_DEF, A79) */
  .vectors : {{ KEEP(*(.vectors)) KEEP(*(.emb_boot_block)) }} > FLASH

  .text : {{
    *(.text .text.*)
    *(.rodata .rodata.*)
    . = ALIGN(16); /* the table entries' own alignment (sizeof(void *) * 4) */
    __start_emb_init_table = .;
    KEEP(*(emb_init_table))
    __stop_emb_init_table = .;
    . = ALIGN(16);
    __start_emb_test_table = .;
    KEEP(*(emb_test_table))
    __stop_emb_test_table = .;
    . = ALIGN(8);
  }} > FLASH

  .ARM.exidx : {{ *(.ARM.exidx* .gnu.linkonce.armexidx.*) }} > FLASH

  /* the interrupt stack, MSP (CONFIG_EMB_ISR_STACK_SIZE, A90): first in RAM, so that an
     overflow runs off the bottom of RAM into a bus fault, not into .data */
  .emb_isr_stack (NOLOAD) : ALIGN(8) {{
    __emb_isr_stack_start = .;
    KEEP(*(.emb_isr_stack))
    __emb_isr_stack_end = .;
  }} > RAM

  __data_load = LOADADDR(.data);
  .data : ALIGN(8) {{
    __data_start = .;
    *(.data .data.*)
    . = ALIGN(8);
    __data_end = .;
  }} > RAM AT > FLASH

  .bss (NOLOAD) : ALIGN(8) {{
    __bss_start = .;
    *(.bss .bss.* COMMON)
    . = ALIGN(8);
    __bss_end = .;
  }} > RAM

  end = .;
  /* the crash record's memory (SPEC-015 §4, A73): above the stack and outside every loaded
     segment, so neither startup nor a loader's reset clears it */
  __emb_retained_end = ORIGIN(RAM) + LENGTH(RAM);
  __emb_retained_start = __emb_retained_end - 192;
  /* below it, 32 bytes the test framework keeps across the resets of its fault checks (A89) */
  __emb_test_retained_end = __emb_retained_start;
  __emb_test_retained_start = __emb_test_retained_end - 32;
  __stack_top = __emb_isr_stack_end;
  ASSERT(end <= __emb_test_retained_start, "RAM overflow: .data and .bss reach the retained memory")
}}
"""


def _ld_size(n):
    if n % (1 << 20) == 0:
        return f"{n >> 20}M"
    if n % (1 << 10) == 0:
        return f"{n >> 10}K"
    return str(n)


def _avr_template():
    return (Path(__file__).resolve().parent / "templates" / "avr5.ld").read_text(encoding="utf-8")


# avr-ld's view of the separate address spaces (avr-libc's linker scripts)
AVR_DATA_VMA = 0x800000
AVR_EEPROM_VMA = 0x810000


_RV_RAM_SECTIONS = """\
OUTPUT_ARCH(riscv)
ENTRY(embn_rv_reset)

MEMORY
{{
  RAM (rwx) : ORIGIN = 0x{ram_origin:08X}, LENGTH = {ram_length}
}}

SECTIONS
{{
  .text : {{
    KEEP(*(.text.embn_rv_reset))
    *(.text .text.*)
  }} > RAM

  .rodata : ALIGN(16) {{
    *(.rodata .rodata.* .srodata .srodata.*)
    . = ALIGN(16); /* the table entries' own alignment (sizeof(void *) * 4) */
    __start_emb_init_table = .;
    KEEP(*(emb_init_table))
    __stop_emb_init_table = .;
    . = ALIGN(16);
    __start_emb_test_table = .;
    KEEP(*(emb_test_table))
    __stop_emb_test_table = .;
  }} > RAM

  .data : ALIGN(16) {{
    *(.data .data.* .sdata .sdata.*)
    /* the GOT, which LLD makes for Clang's medany code: an undefined weak symbol may be 0,
       out of auipc's reach, so Clang loads the table bounds' addresses from it */
    *(.got .got.*)
  }} > RAM

  /* the C library's thread-local block (errno in picolibc), one for every thread: .tdata in
     place, .tbss reserved after it, which the reset clears; tp points at it (A88) */
  /* rv_switch.S puts a word in each, so both exist and the TLS segment starts at .tdata */
  .tdata : ALIGN(16) {{ KEEP(*(.tdata.emb_tls_anchor)) *(.tdata .tdata.* .gnu.linkonce.td.*) }} > RAM
  .tbss : {{ KEEP(*(.tbss.emb_tls_anchor)) *(.tbss .tbss.* .gnu.linkonce.tb.* .tcommon) }} > RAM
  __emb_tls_start = ADDR(.tdata);
  __emb_tbss_start = ADDR(.tdata) + SIZEOF(.tdata);
  __emb_tls_end = ADDR(.tbss) + SIZEOF(.tbss);

  /* placed past .tbss, which takes no room of its own */
  .bss ALIGN(__emb_tls_end, 16) (NOLOAD) : {{
    __bss_start = .;
    *(.bss .bss.* .sbss .sbss.* COMMON)
    . = ALIGN(16);
    __bss_end = .;
  }} > RAM

  end = .;
  /* the crash record's memory (SPEC-015 §4, A73): above the stack and outside every loaded
     segment, so neither startup nor a loader's reset clears it */
  __emb_retained_end = ORIGIN(RAM) + LENGTH(RAM);
  __emb_retained_start = __emb_retained_end - 192;
  /* below it, 32 bytes the test framework keeps across the resets of its fault checks (A89) */
  __emb_test_retained_end = __emb_retained_start;
  __emb_test_retained_start = __emb_test_retained_end - 32;
  __stack_top = __emb_test_retained_start;
}}
"""


def regions_ld(r):
    if r["soc"]["arch"]["port"] == "riscv":
        lk = r["linker"]
        out = "/* SPDX-License-Identifier: Apache-2.0 */\n" + _c_comment(r, _cmd(r))
        out += (f"/* Linker script for {r['board']['name']} ({r['soc'].get('part', r['soc']['name'])}): the image is loaded\n"
                " * into RAM and runs there, so .data needs no copy. The kernel's registration tables are\n"
                " * bracketed by name (SPEC-001 §6.4, HW-006). */\n")
        return out + _RV_RAM_SECTIONS.format(ram_origin=lk["ram"]["origin"], ram_length=_ld_size(lk["ram"]["length"]))
    if r["soc"]["arch"]["port"] == "avr":
        lk = r["linker"]
        eeprom = next((x for x in r["soc"]["memory"]["regions"] if x.get("space") == "eeprom"), None)
        out = "/* SPDX-License-Identifier: Apache-2.0 */\n" + _c_comment(r, _cmd(r))
        out += (f"/* Linker script for {r['board']['name']} ({r['soc'].get('part', r['soc']['name'])}), derived from\n"
                " * avr-libc's avr5 script: text is the app partition, data the SRAM, and the kernel's\n"
                " * registration tables are bracketed in flash (SPEC-012 §8, HW-006). */\n")
        return out + _avr_template().format(
            text_origin=lk["flash"]["origin"], text_length=lk["flash"]["length"],
            data_origin=AVR_DATA_VMA + lk["ram"]["origin"], data_length=lk["ram"]["length"],
            eeprom_origin=AVR_EEPROM_VMA + (eeprom["base"] if eeprom else 0), eeprom_length=eeprom["size"] if eeprom else 0)
    lk = r["linker"]
    out = "/* SPDX-License-Identifier: Apache-2.0 */\n" + _c_comment(r, _cmd(r))
    out += (f"/* Linker script for {r['board']['name']} ({r['soc'].get('part', r['soc']['name'])}): the app "
            f"partition in FLASH, RAM from {' + '.join(lk['ram']['regions'])}. The kernel's registration\n"
            " * tables are bracketed by name (SPEC-001 §6.4, HW-006). */\n")
    out += _CM_SECTIONS.format(flash_origin=lk["flash"]["origin"], flash_length=_ld_size(lk["flash"]["length"]),
                               ram_origin=lk["ram"]["origin"], ram_length=_ld_size(lk["ram"]["length"]))
    return out


