"""The generated outputs of the first increment (SPEC-014 §6, A68): hw_config.h,
board_pins.c, regions.ld, board.conf, board.cmake, hw.json, board.md and build_report.md.

Every output is sorted, carries no timestamp and names the generator version, the schema
version and the SHA-256 of each input (HW-013).
"""
import json

from . import SCHEMA_VERSION, VERSION


def _mhz(hz):
    return f"{hz / 1e6:g} MHz"


def _sym(name):
    return name.upper().replace("-", "_")


def _hex(v):
    return f"0x{v:08X}u"


def _stamp_lines(r, cmd):
    lines = [f"Generated by emb-hwgen {VERSION}, schema v{SCHEMA_VERSION}. Do not edit: change the",
             f"description and run {cmd} (HW-003).",
             "Inputs (SHA-256):"]
    for i in r["inputs"]:
        lines += [f"  {i['path']}", f"    {i['sha256']}"]
    return lines


def _c_comment(r, cmd):
    return "/*\n" + "".join(f" * {line}".rstrip() + "\n" for line in _stamp_lines(r, cmd)) + " */\n"


def _hash_comment(r, cmd):
    return "".join(f"# {line}".rstrip() + "\n" for line in _stamp_lines(r, cmd))


def _cmd(r):
    return f"hw/gen/emb-hwgen.py generate --board {r['board_dir']}"


def _block(title, defs):
    """A comment and its macros, sorted by name and aligned as clang-format aligns them."""
    if not defs:
        return ""
    width = max(len(k) for k in defs)
    out = f"/* {title} */\n"
    for k in sorted(defs):
        out += f"#define {k.ljust(width)} {defs[k]}\n"
    return out + "\n"


# --------------------------------------------------------------------------- hw_config.h

def hw_config_h(r):
    b, soc, clk = r["board"], r["soc"], r["clock"]
    ident = {
        "EMB_HW_BOARD": f'"{b["name"]}"',
        "EMB_HW_SOC": f'"{soc.get("part", soc["name"].upper())}"',
    }
    if "package" in soc:
        ident["EMB_HW_SOC_PACKAGE"] = f'"{soc["package"]}"'

    clocks = {}
    for s in soc.get("clocks", {}).get("sources", []):
        hz = s["hz"]
        if hz == "board":
            osc = b.get("oscillators", {}).get(s["name"])
            if osc is None:
                continue
            hz = osc["hz"]
            clocks[f"EMB_HW_{_sym(s['name'])}_BYPASS"] = "1" if osc["source"] == "external_clock" else "0"
        clocks[f"EMB_HW_{_sym(s['name'])}_HZ"] = f"{hz}u"
    clocks["EMB_HW_CPU_HZ"] = f"{clk['hclk_hz']}u"
    clocks["EMB_HW_SYSCLK_SOURCE"] = f"EMB_HW_SYSCLK_{'PLL' if clk['pll'] else _sym(clk['source'])}"
    clocks["EMB_HW_SYSCLK_HSI"] = "0"
    clocks["EMB_HW_SYSCLK_HSE"] = "1"
    clocks["EMB_HW_SYSCLK_PLL"] = "2"
    if clk["pll"]:
        pll = clk["pll"]
        clocks["EMB_HW_PLL_SOURCE_HSE"] = "1" if clk["source"] == "hse" else "0"
        for f in ("m", "n", "p", "q", "r"):
            if f in pll:
                clocks[f"EMB_HW_PLL_{f.upper()}"] = f"{pll[f]}u"
        clocks["EMB_HW_PLL_VCO_HZ"] = f"{int(pll['vco_hz'])}u"
    clocks["EMB_HW_AHB_DIV"] = f"{clk['ahb_div']}u"
    buses = soc.get("clocks", {}).get("buses", [])
    for bus in buses:
        clocks[f"EMB_HW_{_sym(bus['name'])}_HZ"] = f"{clk['bus_hz'][bus['name']]}u"
        if bus["from"] != "hclk":
            clocks[f"EMB_HW_{_sym(bus['name'])}_DIV"] = f"{clk[bus['from'] + '_div']}u"
    if "flash_wait_states" in clk:
        clocks["EMB_HW_FLASH_WAIT_STATES"] = f"{clk['flash_wait_states']}u"
    if "voltage_scale" in clk:
        clocks["EMB_HW_PWR_VOS"] = f"{clk['voltage_scale']['vos']}u"
        clocks["EMB_HW_PWR_OVERDRIVE"] = "1" if clk["voltage_scale"]["overdrive"] else "0"

    memory = {}
    for reg in soc["memory"]["regions"]:
        memory[f"EMB_HW_{_sym(reg['name'])}_BASE"] = _hex(reg["base"])
        memory[f"EMB_HW_{_sym(reg['name'])}_SIZE"] = f"{reg['size']}u"

    irqs = {
        "EMB_HW_IRQ_COUNT": f"{soc['interrupts']['count']}u",
        "EMB_HW_IRQ_PRIORITY_BITS": f"{soc['interrupts']['priority_bits']}u",
    }

    bus_offset = {bus["name"]: bus.get("enable_offset") for bus in buses}
    periph = {}
    for p in soc["peripherals"]:
        n = _sym(p["name"])
        periph[f"EMB_HW_{n}_BASE"] = _hex(p["base"])
        for irq in p.get("irqs", []):
            suffix = "" if irq["name"] == "global" else "_" + _sym(irq["name"])
            periph[f"EMB_HW_{n}_IRQ{suffix}"] = f"{irq['number']}u"
        clk_gate = p.get("clock")
        if clk_gate is not None and bus_offset.get(clk_gate["bus"]) is not None:
            periph[f"EMB_HW_{n}_CLKEN_OFFSET"] = f"0x{bus_offset[clk_gate['bus']]:02X}u"
            periph[f"EMB_HW_{n}_CLKEN_BIT"] = f"{clk_gate['bit']}u"

    con = r["console"]
    cn = _sym(con["device"])
    console = {
        "EMB_HW_CONSOLE_BASE": f"EMB_HW_{cn}_BASE",
        "EMB_HW_CONSOLE_BAUD": f"{con['baud']}u",
        "EMB_HW_CONSOLE_CLOCK_HZ": f"{con['clock_hz']}u",
        "EMB_HW_CONSOLE_CLKEN_OFFSET": f"EMB_HW_{cn}_CLKEN_OFFSET",
        "EMB_HW_CONSOLE_CLKEN_BIT": f"EMB_HW_{cn}_CLKEN_BIT",
    }
    if any(i["name"] == "global" for i in con["irqs"]):
        console["EMB_HW_CONSOLE_IRQ"] = f"EMB_HW_{cn}_IRQ"

    lines = {}
    pins = {(e["owner"]): e for e in r["pins"]}
    for kind, prefix in (("leds", "LED"), ("buttons", "BUTTON")):
        for i, line in enumerate(b.get(kind, [])):
            e = pins[f"{kind}.{line['name']}"]
            for name in ([f"{prefix}_{_sym(line['name'])}"] + ([prefix] if i == 0 else [])):
                lines[f"EMB_HW_{name}_PORT_BASE"] = f"EMB_HW_{_sym(e['gpio'])}_BASE"
                lines[f"EMB_HW_{name}_CLKEN_BIT"] = f"EMB_HW_{_sym(e['gpio'])}_CLKEN_BIT"
                lines[f"EMB_HW_{name}_PIN"] = f"{e['number']}u"
                lines[f"EMB_HW_{name}_ACTIVE_HIGH"] = "1" if line["active"] == "high" else "0"

    test = {}
    if r["test_irqs"]:
        test = {"EMB_HW_TEST_IRQ": f"{r['test_irqs']['low']}u", "EMB_HW_TEST_IRQ_HIGH": f"{r['test_irqs']['high']}u"}

    out = "/* SPDX-License-Identifier: Apache-2.0 */\n"
    out += _c_comment(r, _cmd(r))
    out += "/* Hardware configuration of " + b["name"] + " (SPEC-014 §6, SPEC-002 §8). */\n"
    out += "#ifndef HW_CONFIG_H\n#define HW_CONFIG_H\n\n"
    out += _block("identity", ident)
    out += _block("clock tree (" + _mhz(clk["hclk_hz"]) + ")", clocks)
    out += _block("memory regions", memory)
    out += _block("interrupt controller", irqs)
    out += _block("peripherals: register blocks, interrupt lines, clock gates", periph)
    out += _block("console: " + con["device"], console)
    out += _block("LEDs and buttons (the first of each also without its name)", lines)
    out += _block("the conformance framework's software interrupts: lines with no peripheral", test)
    out += "#endif /* HW_CONFIG_H */\n"
    return out


# --------------------------------------------------------------------------- board_pins.c

def board_pins_c(r):
    mode = {"af": "EMB_STM32_PIN_AF", "output": "EMB_STM32_PIN_OUTPUT"}
    out = "/* SPDX-License-Identifier: Apache-2.0 */\n"
    out += _c_comment(r, _cmd(r))
    out += ("/* The pins board initialization configures, by port and number. Inputs left at their\n"
            " * reset state (buttons) need no entry. */\n")
    out += "#include <emb_stm32_pins.h>\n#include <hw_config.h>\n\n"
    out += "const emb_stm32_pin_t emb_board_pins[] = {\n"
    entries = [e for e in r["pins"] if e["mode"] in mode]
    for e in entries:
        g = _sym(e["gpio"])
        what = e.get("signal", e["mode"])
        out += f"    /* {e['pin']}: {e['owner']} ({what}) */\n"
        out += (f"    {{EMB_HW_{g}_BASE, EMB_HW_{g}_CLKEN_BIT, {e['number']}u, {mode[e['mode']]}, "
                f"{e.get('af', 0)}u}},\n")
    out += "};\n\n"
    out += "const unsigned emb_board_pin_count = (unsigned)(sizeof(emb_board_pins) / sizeof(emb_board_pins[0]));\n"
    return out


# --------------------------------------------------------------------------- regions.ld

_CM_SECTIONS = """\
ENTRY(embn_cm_reset)

MEMORY
{{
  FLASH (rx)  : ORIGIN = 0x{flash_origin:08X}, LENGTH = {flash_length}
  RAM   (rwx) : ORIGIN = 0x{ram_origin:08X}, LENGTH = {ram_length}
}}

SECTIONS
{{
  .vectors : {{ KEEP(*(.vectors)) }} > FLASH

  .text : {{
    *(.text .text.*)
    *(.rodata .rodata.*)
    . = ALIGN(16); /* the table entries' own alignment (sizeof(void *) * 4) */
    __start_emb_init_table = .;
    KEEP(*(emb_init_table))
    __stop_emb_init_table = .;
    . = ALIGN(16);
    __start_emb_test_table = .;
    KEEP(*(emb_test_table))
    __stop_emb_test_table = .;
    . = ALIGN(8);
  }} > FLASH

  .ARM.exidx : {{ *(.ARM.exidx* .gnu.linkonce.armexidx.*) }} > FLASH

  __data_load = LOADADDR(.data);
  .data : ALIGN(8) {{
    __data_start = .;
    *(.data .data.*)
    . = ALIGN(8);
    __data_end = .;
  }} > RAM AT > FLASH

  .bss (NOLOAD) : ALIGN(8) {{
    __bss_start = .;
    *(.bss .bss.* COMMON)
    . = ALIGN(8);
    __bss_end = .;
  }} > RAM

  end = .;
  __stack_top = ORIGIN(RAM) + LENGTH(RAM);
}}
"""


def _ld_size(n):
    if n % (1 << 20) == 0:
        return f"{n >> 20}M"
    if n % (1 << 10) == 0:
        return f"{n >> 10}K"
    return str(n)


def regions_ld(r):
    lk = r["linker"]
    out = "/* SPDX-License-Identifier: Apache-2.0 */\n" + _c_comment(r, _cmd(r))
    out += (f"/* Linker script for {r['board']['name']} ({r['soc'].get('part', r['soc']['name'])}): the app "
            f"partition in FLASH, RAM from {' + '.join(lk['ram']['regions'])}. The kernel's registration\n"
            " * tables are bracketed by name (SPEC-001 §6.4, HW-006). */\n")
    out += _CM_SECTIONS.format(flash_origin=lk["flash"]["origin"], flash_length=_ld_size(lk["flash"]["length"]),
                               ram_origin=lk["ram"]["origin"], ram_length=_ld_size(lk["ram"]["length"]))
    return out


# --------------------------------------------------------------------------- board.conf, board.cmake

def board_conf(r):
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += f"# Board defaults for {r['board']['name']}. Applied before the profile fragment.\n"
    for k, v in r["kconfig"].items():
        if isinstance(v, bool):
            v = "y" if v else "n"
        out += f"{k}={v}\n"
    return out


def board_cmake(r):
    soc = r["soc"]
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += f"# {r['board']['name']}: {soc.get('part', soc['name'])}, {soc['cpu']['core']} at {_mhz(r['clock']['hclk_hz'])}.\n"
    out += f"set(EMB_BOARD_ARCH {soc['arch']['port']})\n"
    out += f"set(EMB_BOARD_VARIANT {soc['arch']['variant']})\n"
    out += f"set(EMB_BOARD_DEFAULT_PROFILE {r['profile']})\n"
    if soc["cpu"].get("cflags"):
        out += f"set(EMB_BOARD_C_FLAGS {' '.join(soc['cpu']['cflags'])})\n"
    sim = r["board"].get("simulation", {}).get("embsim")
    if sim:
        out += f"set(EMB_BOARD_EMBSIM_TARGET {sim}) # EMB_TEST_EMULATOR=embsim\n"
    out += "# the inputs this directory was generated from, for the configure-time staleness check\n"
    out += "set(EMB_BOARD_HW_INPUTS\n"
    for i in r["inputs"]:
        out += f"    \"{i['path']}={i['sha256']}\"\n"
    out += ")\n"
    return out


# --------------------------------------------------------------------------- hw.json

def hw_json_data(r):
    return {
        "generator": {"name": "emb-hwgen", "version": VERSION},
        "schema_version": SCHEMA_VERSION,
        "inputs": r["inputs"],
        "board": r["board"],
        "soc": r["soc"],
        "derived": {
            "clock": r["clock"],
            "console": r["console"],
            "linker": r["linker"],
            "partitions": r["partitions"],
            "pins": r["pins"],
            "test_irqs": r["test_irqs"],
            "timer": r["timer"],
            "kconfig": r["kconfig"],
            "profile": r["profile"],
        },
        "warnings": r["warnings"],
    }


def hw_json(r):
    return json.dumps(hw_json_data(r), indent=2, sort_keys=True) + "\n"


# --------------------------------------------------------------------------- board.md, build_report.md

def _md_stamp(r):
    out = f"\n---\n\nGenerated by emb-hwgen {VERSION}, schema v{SCHEMA_VERSION}, from:\n\n"
    out += "| Input | SHA-256 |\n|---|---|\n"
    for i in r["inputs"]:
        out += f"| `{i['path']}` | `{i['sha256']}` |\n"
    return out


def board_md(r):
    b, soc, clk = r["board"], r["soc"], r["clock"]
    out = f"# {b['name']}\n\n"
    if b.get("doc"):
        out += b["doc"].strip() + "\n\n"
    out += "| Field | Value |\n|---|---|\n"
    out += f"| SoC | {soc.get('part', soc['name'])} ({soc.get('package', '-')}) |\n"
    out += f"| Core | {soc['cpu']['core']}, port `{soc['arch']['port']}/{soc['arch']['variant']}` |\n"
    if b.get("revision"):
        out += f"| Revision | {b['revision']} |\n"
    out += f"| CPU clock | {_mhz(clk['hclk_hz'])} from {clk['source']}" + (" (bypass)" if clk.get("bypass") else "") + " |\n"
    out += f"| Console | {r['console']['device']} at {r['console']['baud']} baud |\n"
    probe = b.get("debug_probe", {})
    if probe:
        out += "| Debug probe | " + ", ".join(f"{k} `{v}`" for k, v in sorted(probe.items())) + " |\n"
    out += "\n## Memory map\n\n| Region | Base | Size | Attributes |\n|---|---|---|---|\n"
    for reg in sorted(soc["memory"]["regions"], key=lambda x: x["base"]):
        out += f"| {reg['name']} | `0x{reg['base']:08X}` | {_ld_size(reg['size'])} | {', '.join(reg['attrs'])} |\n"
    out += "\n## Flash partitions\n\n| Partition | Base | Size | Erase sectors |\n|---|---|---|---|\n"
    for p in r["partitions"]:
        out += f"| {p['name']} | `0x{p['base']:08X}` | {_ld_size(p['size'])} | {', '.join(map(str, p['sectors']))} |\n"
    out += "\n## Pins\n\n| Pin | Use | Mode |\n|---|---|---|\n"
    for e in r["pins"]:
        m = f"af{e['af']} ({e['signal']})" if e["mode"] == "af" else e["mode"]
        out += f"| {e['pin']} | `{e['owner']}` | {m} |\n"
    out += "\n## Interrupt lines\n\n| Line | Owner |\n|---|---|\n"
    rows = []
    for p in soc["peripherals"]:
        for irq in p.get("irqs", []):
            rows.append((irq["number"], f"{p['name']}.{irq['name']}"))
    if r["test_irqs"]:
        rows += [(r["test_irqs"]["low"], "test framework (low)"), (r["test_irqs"]["high"], "test framework (high)")]
    for n, owner in sorted(rows):
        out += f"| {n} | {owner} |\n"
    return out + _md_stamp(r)


def build_report_md(r):
    clk, soc = r["clock"], r["soc"]
    out = f"# Build report: {r['board']['name']}\n\n## Clock tree\n\n"
    if clk["pll"]:
        p = clk["pll"]
        q = f", Q {p['q']} ({_mhz(p['q_hz'])})" if "q" in p else ""
        rr = f", R {p['r']}" if "r" in p else ""
        out += (f"{clk['source']} {_mhz(clk['source_hz'])} / M {p['m']} = {_mhz(p['vco_in_hz'])} VCO input, "
                f"x N {p['n']} = {_mhz(p['vco_hz'])}, / P {p['p']} = {_mhz(clk['hclk_hz'])}{q}{rr}. "
                f"{'Given by the board, checked' if 'pll' in r['board']['clocks'] else 'Solved'}.\n\n")
    out += "| Bus | Frequency | Limit |\n|---|---|---|\n"
    for bus in soc.get("clocks", {}).get("buses", []):
        out += f"| {bus['name']} | {_mhz(clk['bus_hz'][bus['name']])} | {_mhz(bus['max_hz'])} |\n"
    if "flash_wait_states" in clk:
        out += f"\nFlash wait states: {clk['flash_wait_states']}.\n"
    if "voltage_scale" in clk:
        vs = clk["voltage_scale"]
        out += f"Regulator: {vs['name']} (VOS {vs['vos']}){', over-drive on' if vs['overdrive'] else ''}.\n"
    lk = r["linker"]
    out += "\n## Image layout\n\n| Linker memory | Origin | Length |\n|---|---|---|\n"
    out += f"| FLASH | `0x{lk['flash']['origin']:08X}` | {_ld_size(lk['flash']['length'])} |\n"
    out += f"| RAM ({' + '.join(lk['ram']['regions'])}) | `0x{lk['ram']['origin']:08X}` | {_ld_size(lk['ram']['length'])} |\n"
    out += "\n## Warnings\n\n"
    out += "".join(f"- {w}\n" for w in r["warnings"]) if r["warnings"] else "None.\n"
    return out + _md_stamp(r)


OUTPUTS = {
    "hw_config.h": hw_config_h,
    "board_pins.c": board_pins_c,
    "regions.ld": regions_ld,
    "board.conf": board_conf,
    "board.cmake": board_cmake,
    "hw.json": hw_json,
    "board.md": board_md,
    "build_report.md": build_report_md,
}


def render(resolved):
    return {name: fn(resolved) for name, fn in sorted(OUTPUTS.items())}
