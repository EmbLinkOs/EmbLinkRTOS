def _md_stamp(r):
    out = f"\n---\n\nGenerated by emb-hwgen {VERSION}, schema v{SCHEMA_VERSION}, from:\n\n"
    out += "| Input | SHA-256 |\n|---|---|\n"
    for i in r["inputs"]:
        out += f"| `{i['path']}` | `{i['sha256']}` |\n"
    return out


def board_md(r):
    b, soc, clk = r["board"], r["soc"], r["clock"]
    out = f"# {b['name']}\n\n"
    if b.get("doc"):
        out += b["doc"].strip() + "\n\n"
    out += "| Field | Value |\n|---|---|\n"
    out += f"| SoC | {soc.get('part', soc['name'])} ({soc.get('package', '-')}) |\n"
    out += f"| Core | {soc['cpu']['core']}, port `{soc['arch']['port']}/{soc['arch']['variant']}` |\n"
    if b.get("revision"):
        out += f"| Revision | {b['revision']} |\n"
    out += f"| CPU clock | {_mhz(clk['hclk_hz'])} from {clk['source']}" + (" (bypass)" if clk.get("bypass") else "") + " |\n"
    out += f"| Console | {r['console']['device']} at {r['console']['baud']} baud |\n"
    probe = b.get("debug_probe", {})
    if probe:
        out += "| Debug probe | " + ", ".join(f"{k} `{v}`" for k, v in sorted(probe.items())) + " |\n"
    out += "\n## Memory map\n\n| Region | Base | Size | Attributes |\n|---|---|---|---|\n"
    for reg in sorted(soc["memory"]["regions"], key=lambda x: x["base"]):
        out += f"| {reg['name']} | `0x{reg['base']:08X}` | {_ld_size(reg['size'])} | {', '.join(reg['attrs'])} |\n"
    out += "\n## Flash partitions\n\n| Partition | Base | Size | Erase units |\n|---|---|---|---|\n"
    for p in r["partitions"]:
        if "sectors" in p:
            units = "sectors " + ", ".join(map(str, p["sectors"]))
        elif p.get("pages"):
            units = f"pages {p['pages'][0]} to {p['pages'][1]}"
        else:
            units = "-"
        name = p["name"] + (" (reserved)" if p.get("reserved") else "")
        out += f"| {name} | `0x{p['base']:08X}` | {_ld_size(p['size'])} | {units} |\n"
    out += "\n## Pins\n\n| Pin | Use | Mode |\n|---|---|---|\n"
    for e in r["pins"]:
        m = {"af": f"af{e.get('af')} ({e.get('signal')})", "fixed": f"fixed ({e.get('signal')})"}.get(e["mode"], e["mode"])
        out += f"| {e['pin']} | `{e['owner']}` | {m} |\n"
    if r["devices"]:
        out += "\n## Devices\n\nIn initialization order (SPEC-016 §4).\n\n"
        out += "| Device | Compatible | Class | Level | Depends on |\n|---|---|---|---|---|\n"
        for d in r["devices"]:
            what = d["compatible"] + (f" ({d['peripheral']})" if d["peripheral"] and d["peripheral"] != d["name"] else "")
            deps = ", ".join(d["deps"]) or "-"
            out += f"| {d['name']} | `{what}` | {d['class']} | {d['level'].upper()} | {deps} |\n"
    out += "\n## Interrupt lines\n\n| Line | Owner |\n|---|---|\n"
    rows = []
    for p in soc["peripherals"]:
        for irq in p.get("irqs", []):
            rows.append((irq["number"], f"{p['name']}.{irq['name']}"))
    if r["test_irqs"]:
        rows += [(r["test_irqs"]["low"], "test framework (low)")]
        if r["test_irqs"]["high"] is not None:
            rows += [(r["test_irqs"]["high"], "test framework (high)")]
    for n, owner in sorted(rows):
        out += f"| {n} | {owner} |\n"
    return out + _md_stamp(r)


def build_report_md(r):
    clk, soc = r["clock"], r["soc"]
    out = f"# Build report: {r['board']['name']}\n\n## Clock tree\n\n"
    if clk["pll"]:
        p = clk["pll"]
        q = f", Q {p['q']} ({_mhz(p['q_hz'])})" if "q" in p else ""
        rr = f", R {p['r']}" if "r" in p else ""
        out += (f"{clk['source']} {_mhz(clk['source_hz'])} / M {p['m']} = {_mhz(p['vco_in_hz'])} VCO input, "
                f"x N {p['n']} = {_mhz(p['vco_hz'])}, / P {p['p']} = {_mhz(clk['hclk_hz'])}{q}{rr}. "
                f"{'Given by the board, checked' if 'pll' in r['board']['clocks'] else 'Solved'}.\n\n")
    else:
        out += f"{clk['source']} {_mhz(clk['source_hz'])}, used directly.\n\n"
    buses = soc.get("clocks", {}).get("buses", [])
    if buses:
        out += "| Bus | Frequency | Limit |\n|---|---|---|\n"
    for bus in buses:
        out += f"| {bus['name']} | {_mhz(clk['bus_hz'][bus['name']])} | {_mhz(bus['max_hz'])} |\n"
    if "flash_wait_states" in clk:
        out += f"\nFlash wait states: {clk['flash_wait_states']}.\n"
    if "voltage_scale" in clk:
        vs = clk["voltage_scale"]
        out += f"Regulator: {vs['name']} (VOS {vs['vos']}){', over-drive on' if vs['overdrive'] else ''}.\n"
    lk = r["linker"]
    out += "\n## Image layout\n\n| Linker memory | Origin | Length |\n|---|---|---|\n"
    out += f"| FLASH | `0x{lk['flash']['origin']:08X}` | {_ld_size(lk['flash']['length'])} |\n"
    out += f"| RAM ({' + '.join(lk['ram']['regions'])}) | `0x{lk['ram']['origin']:08X}` | {_ld_size(lk['ram']['length'])} |\n"
    out += "\n## Warnings\n\n"
    out += "".join(f"- {w}\n" for w in r["warnings"]) if r["warnings"] else "None.\n"
    return out + _md_stamp(r)


