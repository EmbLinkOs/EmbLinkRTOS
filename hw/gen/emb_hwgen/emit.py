def embld_opts(r):
    """HW-006: the same layout as regions.ld, as embld options (09 §7)."""
    lk = r["linker"]
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += "# embld options for the same memory map as regions.ld: one option per line.\n"
    out += f"-Ttext=0x{lk['flash']['origin']:X}\n"
    out += f"-Tdata=0x{AVR_DATA_VMA + lk['ram']['origin']:X}\n"
    out += f"--rom-limit={lk['flash']['length']}\n"
    return out


def board_conf(r):
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += f"# Board defaults for {r['board']['name']}. Applied before the profile fragment.\n"
    for k, v in r["kconfig"].items():
        if isinstance(v, bool):
            v = "y" if v else "n"
        out += f"{k}={v}\n"
    return out


def board_cmake(r):
    soc = r["soc"]
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += f"# {r['board']['name']}: {soc.get('part', soc['name'])}, {soc['cpu']['core']} at {_mhz(r['clock']['hclk_hz'])}.\n"
    soc_dir = "soc/" + "/".join(r["board"]["soc"].split("/")[:-1])
    out += f"set(EMB_BOARD_ARCH {soc['arch']['port']})\n"
    out += f"set(EMB_BOARD_VARIANT {soc['arch']['variant']})\n"
    if soc["cpu"].get("mcu"):
        out += f"set(EMB_BOARD_MCU {soc['cpu']['mcu']})\n"
    out += f"set(EMB_BOARD_DEFAULT_PROFILE {r['profile']})\n"
    if soc["cpu"].get("cflags"):
        out += f"set(EMB_BOARD_C_FLAGS {' '.join(soc['cpu']['cflags'])})\n"
    out += "# the SoC family's board support and drivers build this board (generated/CMakeLists.txt)\n"
    if r.get("soc_in_board_root"):
        # the project's own SoC family, beside its boards (A84): generated/ is
        # <root>/boards/<vendor>/<board>/generated
        out += f"get_filename_component(EMB_SOC_DIR \"${{CMAKE_CURRENT_LIST_DIR}}/../../../../{soc_dir}\" ABSOLUTE)\n"
    else:
        out += f"set(EMB_SOC_DIR \"${{EMB_BASE}}/{soc_dir}\")\n"
    out += "set(EMB_BOARD_INCLUDE_DIRS \"${CMAKE_CURRENT_LIST_DIR}\" \"${EMB_SOC_DIR}/include\")\n"
    qemu = r["board"].get("simulation", {}).get("qemu")
    if qemu:
        out += f"set(EMB_BOARD_QEMU_ARGS {' '.join(qemu)})\n"
    resets = r["board"].get("simulation", {}).get("resets_in")
    if resets:
        out += f"set(EMB_BOARD_RESETS_IN {' '.join(resets)}) # restart the image with RAM kept (test_crash_reset)\n"
    sim = r["board"].get("simulation", {}).get("embsim")
    if sim:
        out += f"set(EMB_BOARD_EMBSIM_TARGET {sim}) # EMB_TEST_EMULATOR=embsim\n"
    boot = soc.get("boot")
    if boot:
        out += f"set(EMB_BOARD_FLASH_IMAGE {boot['image']}) # what the SoC's boot ROM loads (A79)\n"
        if "uf2_family" in boot:
            out += f"set(EMB_BOARD_UF2_FAMILY 0x{boot['uf2_family']:08X})\n"
    out += _device_sources(r)
    out += "# the inputs this directory was generated from, for the configure-time staleness check\n"
    out += "set(EMB_BOARD_HW_INPUTS\n"
    for i in r["inputs"]:
        out += f"    \"{i['path']}={i['sha256']}\"\n"
    out += ")\n"
    return out


def _driver_path(r, d, rel):
    if d["origin"] == "board":
        # the board root's own driver (A84): generated/ is <root>/boards/<vendor>/<board>/generated
        return f"${{CMAKE_CURRENT_LIST_DIR}}/../../../../{rel}"
    return f"${{EMB_BASE}}/{rel}"


def _device_sources(r):
    """SPEC-016 §8: the board's devices and the drivers they use, and only those."""
    sources, includes = [], []
    for d in r["devices"]:
        for src in d["sources"]:
            path = _driver_path(r, d, src)
            if path not in sources:
                sources.append(path)
        if d["include"]:
            path = _driver_path(r, d, d["include"])
            if path not in includes:
                includes.append(path)
    out = "# the board's devices (soc_devices.c) and the drivers they use, and only those (SPEC-016 §8)\n"
    out += "set(EMB_BOARD_DRIVER_SOURCES\n    \"${CMAKE_CURRENT_LIST_DIR}/soc_devices.c\"\n"
    out += "".join(f"    \"{s}\"\n" for s in sources) + ")\n"
    if includes:
        out += "set(EMB_BOARD_DRIVER_INCLUDE_DIRS\n" + "".join(f"    \"{i}\"\n" for i in includes) + ")\n"
    return out


def cmakelists_txt(r):
    out = "# SPDX-License-Identifier: Apache-2.0\n" + _hash_comment(r, _cmd(r))
    out += "# The board has no C of its own: its SoC family's board support builds emb_board from\n"
    out += "# board_pins.c and hw_config.h here, and links regions.ld.\n"
    out += "add_subdirectory(\"${EMB_SOC_DIR}\" soc)\n"
    return out


