"""The generated outputs (SPEC-014 §6, A68): hw_config.h, board_pins.c, regions.ld,
board.conf, board.cmake, hw.json, board.md and build_report.md, soc_devices.c and
soc_devices.h, the board's device table (SPEC-016 §8).

Every output is sorted, carries no timestamp and names the generator version, the schema
version and the SHA-256 of each input (HW-013).
"""
import json
import re
import textwrap
from pathlib import Path

from . import SCHEMA_VERSION, VERSION


def _mhz(hz):
    return f"{hz / 1e6:g} MHz"


def _sym(name):
    return name.upper().replace("-", "_")


def _hex(v):
    return f"0x{v:08X}u"


def _stamp_lines(r, cmd):
    lines = [f"Generated by emb-hwgen {VERSION}, schema v{SCHEMA_VERSION}. Do not edit: change the",
             f"description and run {cmd} (HW-003).",
             "Inputs (SHA-256):"]
    for i in r["inputs"]:
        lines += [f"  {i['path']}", f"    {i['sha256']}"]
    return lines


def _c_comment(r, cmd):
    return "/*\n" + "".join(f" * {line}".rstrip() + "\n" for line in _stamp_lines(r, cmd)) + " */\n"


def _hash_comment(r, cmd):
    return "".join(f"# {line}".rstrip() + "\n" for line in _stamp_lines(r, cmd))


def _cmd(r):
    return f"hw/gen/emb-hwgen.py generate --board {r['board_dir']}"


def _block(title, defs):
    """A comment and its macros, sorted by name and aligned as clang-format aligns them."""
    if not defs:
        return ""
    width = max(len(k) for k in defs)
    out = f"/* {title} */\n"
    for k in sorted(defs):
        out += f"#define {k.ljust(width)} {defs[k]}\n"
    return out + "\n"


# --------------------------------------------------------------------------- hw_config.h

def hw_config_h(r):
    b, soc, clk = r["board"], r["soc"], r["clock"]
    ident = {
        "EMB_HW_BOARD": f'"{b["name"]}"',
        "EMB_HW_SOC": f'"{soc.get("part", soc["name"].upper())}"',
    }
    if "package" in soc:
        ident["EMB_HW_SOC_PACKAGE"] = f'"{soc["package"]}"'

    clocks = {}
    for s in soc.get("clocks", {}).get("sources", []):
        hz = s["hz"]
        if hz == "board":
            osc = b.get("oscillators", {}).get(s["name"])
            if osc is None:
                continue
            hz = osc["hz"]
            clocks[f"EMB_HW_{_sym(s['name'])}_BYPASS"] = "1" if osc["source"] == "external_clock" else "0"
        clocks[f"EMB_HW_{_sym(s['name'])}_HZ"] = f"{hz}u"
    clocks["EMB_HW_CPU_HZ"] = f"{clk['hclk_hz']}u"
    has_pll = bool(soc.get("clocks", {}).get("plls"))
    # the STM32 RCC's SYSCLK and PLL source encodings: only for a SoC with its HSI and HSE
    src_names = {s["name"] for s in soc.get("clocks", {}).get("sources", [])}
    if has_pll and {"hsi", "hse"} <= src_names:
        clocks["EMB_HW_SYSCLK_SOURCE"] = f"EMB_HW_SYSCLK_{'PLL' if clk['pll'] else _sym(clk['source'])}"
        clocks["EMB_HW_SYSCLK_HSI"] = "0"
        clocks["EMB_HW_SYSCLK_HSE"] = "1"
        clocks["EMB_HW_SYSCLK_PLL"] = "2"
        # CFGR.SW's encoding; always defined, as the drivers test them with -Wundef
        clocks["EMB_HW_PLL_SOURCE_HSE"] = "1" if clk["pll"] and clk["source"] == "hse" else "0"
    if clk["pll"]:
        pll = clk["pll"]
        for f in ("m", "n", "p", "q", "r", "postdiv1", "postdiv2"):
            if f in pll:
                clocks[f"EMB_HW_PLL_{f.upper()}"] = f"{pll[f]}u"
        clocks["EMB_HW_PLL_VCO_HZ"] = f"{int(pll['vco_hz'])}u"
    buses = soc.get("clocks", {}).get("buses", [])
    if buses:
        clocks["EMB_HW_AHB_DIV"] = f"{clk['ahb_div']}u"
    for bus in buses:
        clocks[f"EMB_HW_{_sym(bus['name'])}_HZ"] = f"{clk['bus_hz'][bus['name']]}u"
        if bus["from"] != "hclk":
            clocks[f"EMB_HW_{_sym(bus['name'])}_DIV"] = f"{clk[bus['from'] + '_div']}u"
    if "flash_wait_states" in clk:
        clocks["EMB_HW_FLASH_WAIT_STATES"] = f"{clk['flash_wait_states']}u"
    if "voltage_scale" in clk:
        clocks["EMB_HW_PWR_VOS"] = f"{clk['voltage_scale']['vos']}u"
        clocks["EMB_HW_PWR_OVERDRIVE"] = "1" if clk["voltage_scale"]["overdrive"] else "0"

    memory = {}
    for reg in soc["memory"]["regions"]:
        memory[f"EMB_HW_{_sym(reg['name'])}_BASE"] = _hex(reg["base"])
        memory[f"EMB_HW_{_sym(reg['name'])}_SIZE"] = f"{reg['size']}u"

    ints = soc["interrupts"]
    irqs, vectors = {}, {}
    if ints["controller"] == "nvic":
        irqs = {"EMB_HW_IRQ_COUNT": f"{ints['count']}u", "EMB_HW_IRQ_PRIORITY_BITS": f"{ints['priority_bits']}u"}
    elif ints["controller"] == "clint":
        irqs = {"EMB_HW_IRQ_COUNT": f"{ints['count']}u"}
    else:
        irqs = {"EMB_HW_VECTOR_COUNT": f"{ints['count']}u"}
        # the port's EMB_ISR(name) pastes EMB_VECTOR_##name (SPEC-012 §7)
        vectors = {f"EMB_VECTOR_{_sym(v['name'])}": str(v["number"]) for v in ints.get("vectors", [])}

    bus_offset = {bus["name"]: bus.get("enable_offset") for bus in buses}
    periph = {}
    for p in soc["peripherals"]:
        n = _sym(p["name"])
        periph[f"EMB_HW_{n}_BASE"] = _hex(p["base"])
        for irq in p.get("irqs", []):
            suffix = "" if irq["name"] == "global" else "_" + _sym(irq["name"])
            periph[f"EMB_HW_{n}_IRQ{suffix}"] = f"{irq['number']}u"
        clk_gate = p.get("clock")
        if clk_gate is not None and bus_offset.get(clk_gate["bus"]) is not None:
            periph[f"EMB_HW_{n}_CLKEN_OFFSET"] = f"0x{bus_offset[clk_gate['bus']]:02X}u"
            periph[f"EMB_HW_{n}_CLKEN_BIT"] = f"{clk_gate['bit']}u"

    con = r["console"]
    cn = _sym(con["device"])
    console = {
        "EMB_HW_CONSOLE_BASE": f"EMB_HW_{cn}_BASE",
        "EMB_HW_CONSOLE_BAUD": f"{con['baud']}u",
        "EMB_HW_CONSOLE_CLOCK_HZ": f"{con['clock_hz']}u",
    }
    if con["clock"]:
        console["EMB_HW_CONSOLE_CLKEN_OFFSET"] = f"EMB_HW_{cn}_CLKEN_OFFSET"
        console["EMB_HW_CONSOLE_CLKEN_BIT"] = f"EMB_HW_{cn}_CLKEN_BIT"
    if any(i["name"] == "global" for i in con["irqs"]):
        console["EMB_HW_CONSOLE_IRQ"] = f"EMB_HW_{cn}_IRQ"

    lines = {}
    pins = {(e["owner"]): e for e in r["pins"]}
    gated = {p["name"] for p in soc["peripherals"] if p.get("clock")}
    for kind, prefix in (("leds", "LED"), ("buttons", "BUTTON")):
        for i, line in enumerate(b.get(kind, [])):
            e = pins[f"{kind}.{line['name']}"]
            for name in ([f"{prefix}_{_sym(line['name'])}"] + ([prefix] if i == 0 else [])):
                lines[f"EMB_HW_{name}_PORT_BASE"] = f"EMB_HW_{_sym(e['gpio'])}_BASE"
                if e["gpio"] in gated:
                    lines[f"EMB_HW_{name}_CLKEN_BIT"] = f"EMB_HW_{_sym(e['gpio'])}_CLKEN_BIT"
                lines[f"EMB_HW_{name}_PIN"] = f"{e['number']}u"
                lines[f"EMB_HW_{name}_ACTIVE_HIGH"] = "1" if line["active"] == "high" else "0"

    test = {}
    if r["test_irqs"]:
        test = {"EMB_HW_TEST_IRQ": f"{r['test_irqs']['low']}u"}
        if r["test_irqs"]["high"] is not None:
            test["EMB_HW_TEST_IRQ_HIGH"] = f"{r['test_irqs']['high']}u"

    out = "/* SPDX-License-Identifier: Apache-2.0 */\n"
    out += _c_comment(r, _cmd(r))
    out += "/* Hardware configuration of " + b["name"] + " (SPEC-014 §6, SPEC-002 §8). */\n"
    out += "#ifndef HW_CONFIG_H\n#define HW_CONFIG_H\n\n"
    out += _block("identity", ident)
    out += _block("clock tree (" + _mhz(clk["hclk_hz"]) + ")", clocks)
    out += _block("memory regions", memory)
    out += _block("interrupt controller", irqs)
    out += _block("interrupt vectors, numbered from zero", vectors)
    out += _block("peripherals: register blocks, interrupt lines, clock gates", periph)
    out += _block("console: " + con["device"], console)
    out += _block("LEDs and buttons (the first of each also without its name)", lines)
    out += _block("the conformance framework's software interrupts: lines with no peripheral", test)
    out += "#endif /* HW_CONFIG_H */\n"
    return out


# --------------------------------------------------------------------------- board_pins.c

def board_pins_c(r):
    mode = {"af": "EMB_STM32_PIN_AF", "output": "EMB_STM32_PIN_OUTPUT"}
    out = "/* SPDX-License-Identifier: Apache-2.0 */\n"
    out += _c_comment(r, _cmd(r))
    out += ("/* The pins board initialization configures, by port and number. Inputs left at their\n"
            " * reset state (buttons) need no entry. */\n")
    out += "#include <emb_stm32_pins.h>\n#include <hw_config.h>\n\n"
    out += "const emb_stm32_pin_t emb_board_pins[] = {\n"
    entries = [e for e in r["pins"] if e["mode"] in mode]
    for e in entries:
        g = _sym(e["gpio"])
        what = e.get("signal", e["mode"])
        out += f"    /* {e['pin']}: {e['owner']} ({what}) */\n"
        out += f"    {{EMB_STM32_PORT({e['port']}), {e['number']}u, {mode[e['mode']]}, {e.get('af', 0)}u}},\n"
    out += "};\n\n"
    out += "const unsigned emb_board_pin_count = (unsigned)(sizeof(emb_board_pins) / sizeof(emb_board_pins[0]));\n"
    return out


